interface LangCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string) => string
  /** Translate an enum code within a group, e.g. te('st', 'scheduled') */
  te: (group: string, code: string | null | undefined) => string
}

const LanguageContext = createContext<LangCtx>({
  lang: 'ar',
  setLang: () => {},
  t: (k) => k,
  te: (_g, c) => c || '',
})

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(
    (localStorage.getItem('lang') as Lang) || 'ar',
  )

  const setLang = (l: Lang) => {
    localStorage.setItem('lang', l)
    setLangState(l)
  }

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])

  const t = (key: string) => DICT[key]?.[lang] ?? key
  const te = (group: string, code: string | null | undefined) =>
    code ? (DICT[`${group}_${code}`]?.[lang] ?? code) : ''

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, te }}>
      {children}
    </LanguageContext.Provider>
  )
}

export const useLang = () => useContext(LanguageContext)

/** Current language outside React (for utils like money/print). */
export const currentLang = (): Lang => (localStorage.getItem('lang') as Lang) || 'ar'
